#!/usr/bin/env python3
"""Builds docs/thesis/scanner-results-tables.docx: the RQ2/RQ3 comparison tables for the
executed scanner experiments E3 (role-aware), E4 (status-only) and E5 (VAmPI), alongside
OWASP ZAP (E1/E2).

Every number is read from the archived comparison metrics in evaluation/results/; nothing
is typed in by hand. Styles come from the Savonia reporting template.

Usage: python3 docs/thesis/build_scanner_tables.py
"""
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from docx_tables import TableDocument  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs' / 'thesis' / 'scanner-results-tables.docx'
TESTAPI = ROOT / 'evaluation/results/2026-11-21-scanner-test-api'
VAMPI = ROOT / 'evaluation/results/2026-11-21-scanner-vampi'
ABLATION = ROOT / 'evaluation/results/2026-11-21-ablation-e6'
LABELS = {
    'PRIMARY': 'BOLA + BFLA', 'BOLA': 'BOLA', 'BFLA': 'BFLA',
    'SECONDARY': 'Authentication / JWT', 'OVERALL': 'All categories',
}


def fmt(v):
    return 'n/a' if v is None else f'{v:.3f}'


def metrics(comparison_dir):
    return json.loads((Path(comparison_dir) / 'metrics.json').read_text())


def comparison_table(out, caption, report, scopes, note=None):
    rows = []
    for scope in scopes:
        for r in report['results']:
            m = r['metrics']['confirmed'].get(scope)
            if not m:
                continue
            rows.append([LABELS.get(scope, scope), r['name'], m['tp'], m['fp'], m['tn'], m['fn'],
                         fmt(m['precision']), fmt(m['recall']), fmt(m['f1']), fmt(m['falsePositiveRate'])])
    out.table(caption, ['Scope', 'Approach', 'TP', 'FP', 'TN', 'FN', 'Precision', 'Recall', 'F1', 'FPR'], rows,
              [2.5, 2.3, 0.8, 0.8, 0.9, 0.9, 1.5, 1.4, 1.4, 1.4],
              note=note or 'Threshold: confirmed findings. n/a = undefined because the denominator is zero.')


out = TableDocument()
out.heading('SCANNER RESULTS TABLES (RQ2, RQ3)')
out.para('Generated by docs/thesis/build_scanner_tables.py from the archived comparison metrics in '
         'evaluation/results/. The role-aware and status-only approaches run from one shared test plan, so they '
         'send the same requests; only the decision rule differs.')

bench = metrics(TESTAPI / 'comparison')
comparison_table(out, 'RQ2 - benchmark API (vulnerable build): detection quality by approach',
                 bench, ['PRIMARY', 'BOLA', 'BFLA', 'SECONDARY', 'OVERALL'])

vampi = metrics(VAMPI / 'comparison')
comparison_table(out, 'RQ2 - VAmPI (vulnerable mode): detection quality by approach',
                 vampi, ['PRIMARY', 'BOLA', 'BFLA', 'OVERALL'],
                 note='Threshold: confirmed findings. The role-aware oracle misses one blind cross-user password '
                      'change (PUT /users/v1/{username}/password) whose effect is not observable through the API. '
                      'On VAmPI the status-only baseline keeps precision 1.000 because VAmPI has almost no '
                      'legitimate 2xx-to-forbidden responses, unlike the benchmark.')

# Headline summary (overall, both targets)
rows = []
for target, rep in [('Benchmark API', bench), ('VAmPI', vampi)]:
    for r in rep['results']:
        m = r['metrics']['confirmed']['OVERALL']
        rows.append([target, r['name'], fmt(m['precision']), fmt(m['recall']), fmt(m['f1']), fmt(m['falsePositiveRate']),
                     f"{m['tp']}/{m['tp'] + m['fn']}"])
out.table('RQ2 summary - overall detection quality per target and approach',
          ['Target', 'Approach', 'Precision', 'Recall', 'F1', 'FPR', 'Detected'], rows,
          [3.0, 2.6, 1.7, 1.5, 1.3, 1.3, 1.6])

# E6 ablation
ablation = metrics(ABLATION / 'comparison')
comparison_table(out, 'E6 ablation - benchmark API without x-access-control annotations',
                 ablation, ['PRIMARY', 'SECONDARY', 'OVERALL'],
                 note='Threshold: confirmed findings. "No policy source" = the spec annotations removed and no '
                      'config accessRules supplied; the tool then generates no BOLA/BFLA tests but raises no false '
                      'positives, and still finds the authentication flaws (from the spec security requirement). '
                      '"Config rules, no annotations" supplies the same policy through configuration and fully '
                      'restores detection. The tool depends on a declared policy source (spec or config), not '
                      'specifically on OpenAPI annotations.')

# RQ3 timing
timing = list(csv.DictReader((TESTAPI / 'rq3-timing.csv').open()))
durations = [int(r['durationMs']) for r in timing]
mean = sum(durations) / len(durations)
sd = (sum((d - mean) ** 2 for d in durations) / len(durations)) ** 0.5
reqs = timing[0]['requests']
out.table('RQ3 - cost of one scan of the benchmark API (role-aware oracle, n = 5)',
          ['Metric', 'Value'],
          [['HTTP requests per run', f'{reqs} (deterministic across all 5 runs)'],
           ['Execution time, mean', f'{mean:.0f} ms'],
           ['Execution time, standard deviation', f'{sd:.0f} ms'],
           ['Target', 'localhost (Docker), warm'],
           ['CI integration', 'runs unattended in GitHub Actions; exit code gates the pipeline']],
          [6.0, 10.0],
          note='Per-run figures from evaluation/results/2026-11-21-scanner-test-api/rq3-timing.csv.')

# E7 - CI pipeline run (RQ3 CI suitability). Facts from the archived run in
# evaluation/results/2026-11-21-ci-e7/ (GitHub Actions run #29 on main).
out.table('E7 - the scanner in a GitHub Actions pipeline (RQ3, CI suitability)',
          ['Pipeline stage', 'Outcome'],
          [['Unit and integration tests (80 tests)', 'passed'],
           ['Start both benchmark builds (:3000, :3001) and wait for health', 'passed'],
           ['Run the access-control scan (scan:ci)', 'passed'],
           ['Security gate on the patched build (report --fail-on high)', 'passed (exit 0)'],
           ['Detection regression check on the vulnerable build', 'passed'],
           ['Upload reports as a build artifact', 'passed'],
           ['Total wall time (GitHub-hosted runner)', 'approximately 40 s']],
          [9.5, 6.5],
          note='Reference run #29 on main; 29 workflow runs completed. The gate fails the pipeline on a confirmed '
               'high/critical access-control finding (process exit code). Record: evaluation/results/2026-11-21-ci-e7/.')

# E8 - crAPI findings by category (applicability demonstration, not scored).
crapi = json.loads((ROOT / 'evaluation/results/2026-11-21-crapi-e8/crapi-findings.json').read_text())
CAT_LABEL = {'BOLA': 'Broken object level authorization', 'BFLA': 'Broken function level authorization',
             'AUTH_MISSING': 'Missing authentication', 'AUTH_INVALID_TOKEN': 'Malformed token accepted',
             'JWT_SIGNATURE': 'JWT signature not verified', 'JWT_NONE_ALG': 'Unsigned (alg:none) token accepted',
             'JWT_EXPIRED': 'Expired token accepted'}
counts = {}
for f in crapi['findings']:
    counts[f['category']] = counts.get(f['category'], 0) + 1
order = ['BOLA', 'BFLA', 'AUTH_MISSING', 'AUTH_INVALID_TOKEN', 'JWT_SIGNATURE', 'JWT_NONE_ALG', 'JWT_EXPIRED']
rows = [[c, CAT_LABEL[c], counts[c]] for c in order if c in counts]
rows.append(['Total', '', len(crapi['findings'])])
out.table('E8 - findings on OWASP crAPI (applicability demonstration, not scored)',
          ['Category', 'Description', 'Confirmed findings'], rows, [3.4, 9.6, 3.0],
          note=f"Configuration only (crAPI has no x-access-control annotations); {crapi['meta']['requests']} requests, "
               f"{crapi['meta']['durationMs'] / 1000:.1f} s. No precision/recall is claimed for crAPI. Two headline "
               'findings were spot-verified: the vehicle-location BOLA (a user read a seeded vehicle owned by another '
               'account) and the alg:none JWT bypass (a forged unsigned token returned the dashboard). The 15 unsigned-'
               'token findings share one root cause. Record: evaluation/results/2026-11-21-crapi-e8/.')

out.save(OUT)
print(f'Wrote {OUT} ({out.table_no} tables)')
