#!/usr/bin/env python3
"""Builds docs/thesis/methodology-tables.docx: thesis-ready tables for the methodology
chapter (design science framing, benchmark design, ground truth, metrics, experiments,
environment, implemented components).

Data-bearing tables are read from the repository (ground-truth manifests, seed data,
OpenAPI spec, package lock, evaluation/README.md, docs/ARCHITECTURE.md), so they stay in
sync with the artifact. The design tables (DSR mapping, counting rules, metrics) restate
decisions documented in docs/DECISIONS.md and evaluation/README.md.

Usage: python3 docs/thesis/build_methodology_tables.py
"""
import json
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from docx_tables import TableDocument  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs' / 'thesis' / 'methodology-tables.docx'
CATEGORY_LABELS = {
    'BOLA': 'Broken Object Level Authorization', 'BFLA': 'Broken Function Level Authorization',
    'AUTH_MISSING': 'Missing authentication', 'AUTH_INVALID_TOKEN': 'Malformed token accepted',
    'JWT_SIGNATURE': 'JWT signature not verified', 'JWT_NONE_ALG': 'Unsigned JWT accepted',
    'JWT_EXPIRED': 'Expired JWT accepted',
}
ORDER = list(CATEGORY_LABELS)


def read_json(rel):
    return json.loads((ROOT / rel).read_text())


def node(script):
    return subprocess.run(['node', '--input-type=module', '-e', script], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def markdown_table(path, first_header):
    """Rows of the first markdown table in `path` whose header starts with `first_header`."""
    lines = (ROOT / path).read_text().splitlines()
    rows, inside = [], False
    for line in lines:
        if line.startswith(f'| {first_header}'):
            inside = True
            continue
        if inside:
            if not line.startswith('|'):
                break
            if set(line.replace('|', '').strip()) <= set('-: '):
                continue
            rows.append([c.strip() for c in line.strip().strip('|').split('|')])
    return rows


def plain(md):
    return re.sub(r'\*\*|`', '', md)


gt = read_json('test-api/ground-truth.json')
gt_sec = read_json('test-api/ground-truth.secure.json')
vampi = read_json('benchmarks/vampi/ground-truth.json')
vampi_sec = read_json('benchmarks/vampi/ground-truth.secure.json')
seed = json.loads(subprocess.run(['node', 'test-api/seeds/seed.js', '--json'], cwd=ROOT, check=True, capture_output=True, text=True).stdout)
ops = json.loads(node("import { loadSpec, listOperations } from './cli-tool/src/parser/openapi.js';"
                      "const o = listOperations(loadSpec('test-api/openapi.yaml'));"
                      "console.log(JSON.stringify({ total: o.length, auth: o.filter(x => x.requiresAuth).length,"
                      " owner: o.filter(x => x.accessControl?.ownership === 'owner').length }));"))
lock = read_json('package-lock.json')['packages']
e1 = read_json('evaluation/results/2026-11-20-zap-test-api/vulnerable/zap-report.json')

out = TableDocument()
out.heading('METHODOLOGY TABLES')
out.para('Generated by docs/thesis/build_methodology_tables.py from the repository. Data tables are read from the '
         'artifact itself; edit wording as needed when moving the tables into the thesis.')

# 1 DSR mapping
out.table('Design Science Research activities and their realisation in this thesis',
          ['DSR activity (Peffers et al. 2007)', 'Realisation in this thesis', 'Repository evidence'],
          [['1 Problem identification and motivation', 'BOLA and BFLA are hard to detect for scanners that do not know object ownership or role policy', 'Topic proposal; theory chapter'],
           ['2 Objectives of a solution', 'Detect BOLA/BFLA from an OpenAPI specification and several accounts, with few false positives, fast enough for CI', 'Research questions RQ1–RQ3'],
           ['3 Design and development', 'Benchmark API, role-aware testing tool, reporting, CI workflow', 'test-api/, cli-tool/, .github/workflows/'],
           ['4 Demonstration', 'Runs against the benchmark and VAmPI in Docker', 'docker-compose.yml, evaluation/results/'],
           ['5 Evaluation', 'Precision, recall, F1, FPR, time and requests against a ground truth; comparison with OWASP ZAP and a status-only baseline', 'evaluation/, ground-truth manifests'],
           ['6 Communication', 'Thesis report and public repository', 'README.md, docs/']],
          [4.3, 7.2, 4.5])

# 2 Roles
out.table('Roles of the benchmark API',
          ['Role', 'Intended permissions'],
          [['admin', 'All functions, including administrative functions; may access every object'],
           ['user', 'Regular customer: creates and manages own objects; no administrative functions'],
           ['guest', 'Authenticated, read-only: may not create objects; no administrative functions'],
           ['(anonymous)', 'Only public operations (health check, login, product catalogue)']],
          [3.0, 13.0])

# 3 Accounts (no passwords in the thesis)
acc_rows = [[a['id'], a['username'], a['role'], 'yes' if a['username'] in ('admin', 'alice', 'bob', 'guest') else 'no (data owner only)']
            for a in seed['accounts']]
out.table('Synthetic seed accounts of the benchmark API', ['ID', 'Username', 'Role', 'Configured as test account'], acc_rows,
          [1.5, 3.5, 3.0, 8.0], note='Passwords are synthetic and listed in the repository (test-api/src/data/seed-data.js).')

# 4 Benchmark size
summary = seed['summary']
out.table('Size of the benchmark API',
          ['Item', 'Count'],
          [['OpenAPI operations', ops['total']],
           ['Operations requiring authentication', ops['auth']],
           ['Operations with an owner-only object policy', ops['owner']],
           ['Injected flaws (one per vulnerable ground-truth case)', len([c for c in gt['cases'] if c['vulnerable']])],
           ['Seeded orders / invoices / documents / IoT devices', f"{summary['orders']} / {summary['invoices']} / {summary['documents']} / {summary['devices']}"]],
          [11.0, 5.0])

# 5 Injected flaws by category
vuln = [c for c in gt['cases'] if c['vulnerable']]
out.table('Injected flaws in the vulnerable build, by category',
          ['Category', 'Operation', 'Kind', 'Flaw ID'],
          [[c['category'], f"{c['method']} {c['path']}", c.get('kind', ''), c['flawId']] for c in vuln],
          [3.7, 5.3, 1.4, 5.6],
          note='Every flaw is switched off in the patched build (FLAWS=none). Flaw descriptions: test-api/src/flaws.js.')

# 6 True-negative patterns
tn = [c for c in gt['cases'] if not c['vulnerable'] and c.get('notes', '').startswith('True-negative pattern')]
out.table('Correctly protected operations that still answer with a 2xx status (true-negative patterns)',
          ['Operation', 'Category', 'Correct behaviour'],
          [[f"{c['method']} {c['path']}", c['category'], c['notes'].replace('True-negative pattern. ', '')] for c in tn],
          [5.6, 1.8, 8.6],
          note='These cases separate an oracle that inspects response content and ownership from one that checks only HTTP status codes.')

# 7 Ground-truth summary
def counts(g):
    s = g['summary']
    return {k: f"{v['vulnerable']} / {v['secure']}" for k, v in s.items()}
cols = [counts(gt), counts(gt_sec), counts(vampi), counts(vampi_sec)]
rows = [[CATEGORY_LABELS[k], *[c.get(k, '–') for c in cols]] for k in ORDER]
rows.append(['Scored cases (vulnerable)', *[f"{g['totals']['scored']} ({g['totals']['vulnerable']})" for g in (gt, gt_sec, vampi, vampi_sec)]])
out.table('Ground truth: vulnerable / secure cases per category',
          ['Category', 'Benchmark, vulnerable build', 'Benchmark, patched build', 'VAmPI, vulnerable mode', 'VAmPI, patched mode'],
          rows, [4.4, 2.9, 2.9, 2.9, 2.9],
          note=f"Benchmark vulnerable build: {gt['totals']['excluded']} further cases are excluded from scoring by the root-cause rule (Table 8).")

# 8 Counting rules
out.table('Ground-truth unit of analysis and counting rules',
          ['Rule', 'Definition'],
          [['Case', 'One (HTTP method, OpenAPI path template, category) with a known label: vulnerable or secure'],
           ['Detection', 'A tool detects a case when at least one of its findings has the same method, path template and category'],
           ['BOLA applicability', 'Operations whose intended policy restricts access to the owner of the addressed object'],
           ['BFLA applicability', 'Non-public operations whose intended roles exclude at least one role and that have no ownership rule'],
           ['Authentication applicability', 'Every operation that requires authentication, for each authentication/JWT category'],
           ['Root-cause rule', 'Where a broader authentication flaw exists on an operation, the narrower authentication categories on that operation are excluded from scoring'],
           ['Unlisted findings', 'A finding that matches no case counts as a false positive'],
           ['Independence', 'Labels are fixed from the benchmark design before any tool is run and are checked by automated consistency tests']],
          [4.0, 12.0])

# 9 Metrics
out.table('Evaluation metrics',
          ['Metric', 'Definition', 'Research question'],
          [['Precision', 'TP / (TP + FP)', 'RQ2'],
           ['Recall (detection rate)', 'TP / (TP + FN)', 'RQ2'],
           ['F1 score', '2 · Precision · Recall / (Precision + Recall)', 'RQ2'],
           ['False-positive rate', 'FP / (FP + TN)', 'RQ2'],
           ['Execution time', 'Wall-clock duration of one run', 'RQ3'],
           ['Number of requests', 'HTTP requests sent during one run', 'RQ3'],
           ['CI suitability', 'Runs unattended in GitHub Actions; exit code gates the pipeline', 'RQ3']],
          [3.8, 9.2, 3.0],
          note='A metric whose denominator is zero is reported as undefined (n/a), never as 0 or 1. Metrics are reported per '
               'category, for BOLA+BFLA and for authentication/JWT, at two thresholds: confirmed findings only, and confirmed plus potential findings.')

# 10 Experiments (status from evaluation/README.md)
exp = markdown_table('evaluation/README.md', 'ID')
out.table('Planned and executed experiments', ['ID', 'Description', 'Status'],
          [[r[0], plain(r[1]), plain(r[2]).split(':')[0]] for r in exp], [1.2, 10.3, 4.5],
          note='Status as recorded in evaluation/README.md. Only executed experiments have results.')

# 11 Environment
zap_version = e1.get('@version', '')
out.table('Software used in the implementation and the experiments',
          ['Software', 'Version', 'Role'],
          [['Node.js', subprocess.run(['node', '--version'], capture_output=True, text=True).stdout.strip(), 'Runtime of the benchmark API, the tool and the evaluation'],
           ['Express', lock['node_modules/express']['version'], 'Web framework of the benchmark API'],
           ['jsonwebtoken', lock['node_modules/jsonwebtoken']['version'], 'Token issuing and verification in the benchmark API'],
           ['yaml', lock['node_modules/yaml']['version'], 'Reading OpenAPI and configuration files'],
           ['OWASP ZAP', zap_version, 'Comparison tool (Docker image ghcr.io/zaproxy/zaproxy:stable)'],
           ['VAmPI', 'erev0s/vampi:latest (2026-11-20)', 'External benchmark application'],
           ['Docker / Docker Compose', 'see docker-compose.yml', 'Isolated local test environment'],
           ['GitHub Actions', 'workflow security-scan.yml', 'CI pipeline']],
          [3.4, 4.2, 8.4])

# 12 Components (from docs/ARCHITECTURE.md)
comp = markdown_table('docs/ARCHITECTURE.md', 'Component')
out.table('Components of the artifact and their status', ['Component', 'Location', 'Status'],
          [[plain(r[0]), plain(r[1]), plain(r[3])] for r in comp], [4.0, 6.5, 5.5],
          note='Status as recorded in docs/ARCHITECTURE.md.')

out.save(OUT)
print(f'Wrote {OUT} ({out.table_no} tables)')
