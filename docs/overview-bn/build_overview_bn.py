"""Builds docs/overview-bn/Project-Overview-Bangla.docx — a complete Bangla (বাংলা)
explainer of the whole project: concepts, definitions, design, every experiment and result.

Standalone document (not the Savonia thesis). Uses Noto Sans Bengali for correct shaping.
Usage: python3 docs/overview-bn/build_overview_bn.py
"""
from pathlib import Path
import docx
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml import OxmlElement
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor, Cm

OUT = Path(__file__).resolve().parent / 'Project-Overview-Bangla.docx'
BN = 'Noto Sans Bengali'
INK = RGBColor(0x1d, 0x1f, 0x23)
MUTED = RGBColor(0x5b, 0x61, 0x6b)
ACCENT = RGBColor(0x1b, 0x4b, 0x8a)

doc = docx.Document()
for s in doc.sections:
    s.top_margin = s.bottom_margin = Cm(2.2)
    s.left_margin = s.right_margin = Cm(2.2)


def _font(run, size=11.5, bold=False, color=INK, italic=False):
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = color
    rpr = run._r.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rpr.insert(0, rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rf.set(qn(a), BN)
    szcs = OxmlElement('w:szCs')
    szcs.set(qn('w:val'), str(int(size * 2)))
    rpr.append(szcs)


def para(text, size=11.5, bold=False, color=INK, italic=False, after=6, before=0, align=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.line_spacing = 1.25
    if align:
        p.alignment = align
    _font(p.add_run(text), size, bold, color, italic)
    return p


def h1(text):
    para(text, size=17, bold=True, color=ACCENT, before=16, after=8)


def h2(text):
    para(text, size=13.5, bold=True, color=ACCENT, before=12, after=5)


def bullet(text, bold_prefix=None):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(3)
    p.paragraph_format.line_spacing = 1.2
    if bold_prefix:
        _font(p.add_run(bold_prefix), 11.5, True)
        _font(p.add_run(text), 11.5)
    else:
        _font(p.add_run(text), 11.5)


def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.autofit = False
    for i, c in enumerate(t._tbl.tblGrid.findall(qn('w:gridCol'))):
        c.set(qn('w:w'), str(int(Cm(widths[i]).twips)))
    for i, htext in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ''
        _font(cell.paragraphs[0].add_run(htext), 10.5, True)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ''
            _font(cells[i].paragraphs[0].add_run(str(v)), 10)
    for row in t.rows:
        for i, cell in enumerate(row.cells):
            cell.width = Cm(widths[i])
            for p in cell.paragraphs:
                p.paragraph_format.space_before = Pt(1)
                p.paragraph_format.space_after = Pt(1)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def toc():
    p = doc.add_paragraph()
    r1 = p.add_run()
    f = OxmlElement('w:fldChar'); f.set(qn('w:fldCharType'), 'begin'); r1._r.append(f)
    r2 = p.add_run()
    it = OxmlElement('w:instrText'); it.set(qn('xml:space'), 'preserve'); it.text = 'TOC \\o "1-2" \\h \\z \\u'; r2._r.append(it)
    r3 = p.add_run()
    f2 = OxmlElement('w:fldChar'); f2.set(qn('w:fldCharType'), 'separate'); r3._r.append(f2)
    _font(p.add_run('এই লাইনে রাইট-ক্লিক করে "Update Field" চাপলে সূচিপত্র তৈরি হবে।'), 10.5, italic=True, color=MUTED)
    r5 = p.add_run()
    f3 = OxmlElement('w:fldChar'); f3.set(qn('w:fldCharType'), 'end'); r5._r.append(f3)


# Make the built-in Heading styles use the Bengali font too (so the TOC field picks them up).
for name in ('Heading 1', 'Heading 2'):
    st = doc.styles[name]
    rpr = st.element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts')
        rpr.insert(0, rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs'):
        rf.set(qn(a), BN)


def heading(text, level):
    # Real heading (for the TOC field) with Bengali font applied to its run.
    p = doc.add_paragraph(style=f'Heading {level}')
    p.paragraph_format.space_before = Pt(16 if level == 1 else 11)
    p.paragraph_format.space_after = Pt(7 if level == 1 else 4)
    _font(p.add_run(text), 17 if level == 1 else 13.5, True, ACCENT)


