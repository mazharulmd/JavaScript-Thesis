#!/usr/bin/env node
/**
 * E6 ablation inputs. Produces, from test-api/openapi.yaml:
 *   evaluation/datasets/openapi.no-annotations.yaml  — the spec with every x-access-control removed
 *   evaluation/datasets/ablation.config.yaml         — example config + accessRules re-encoding the
 *                                                       same policy (as a tester configures a real API)
 * Usage: node evaluation/datasets/build-ablation.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { parse, stringify } from 'yaml';

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const doc = parse(readFileSync('test-api/openapi.yaml', 'utf8'));
const rules = [];
let stripped = 0;
for (const [path, item] of Object.entries(doc.paths)) {
  for (const m of METHODS) {
    const op = item[m];
    if (!op?.['x-access-control']) continue;
    const ac = op['x-access-control'];
    const isPublic = Array.isArray(op.security) && op.security.length === 0;
    if (!isPublic && (ac.ownership === 'owner' || (Array.isArray(ac.roles) && ac.roles.length < 3))) {
      const rule = { path, methods: [m.toUpperCase()] };
      if (Array.isArray(ac.roles)) rule.roles = ac.roles;
      if (ac.ownership) rule.ownership = ac.ownership;
      if (ac.ownerField) rule.ownerField = ac.ownerField;
      rules.push(rule);
    }
    delete op['x-access-control'];
    stripped += 1;
  }
}
writeFileSync('evaluation/datasets/openapi.no-annotations.yaml',
  '# E6 ablation: test-api/openapi.yaml with every x-access-control annotation removed.\n' +
  '# Generated by evaluation/datasets/build-ablation.mjs. Security (auth) requirements are kept.\n' +
  stringify(doc));
const cfg = parse(readFileSync('cli-tool/config/example.config.yaml', 'utf8'));
cfg.accessRules = rules;
writeFileSync('evaluation/datasets/ablation.config.yaml',
  '# E6 ablation variant B: policy supplied via config accessRules (as a tester would for an\n' +
  '# un-annotated real API), used with evaluation/datasets/openapi.no-annotations.yaml.\n' +
  stringify(cfg));
console.log(`Stripped ${stripped} annotations; derived ${rules.length} accessRules.`);
